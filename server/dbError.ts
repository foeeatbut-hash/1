// Отказ базы человеческим языком.
//
// Написано по случаю, стоившему рабочего дня: в настройках перестали
// заводиться роли и их доступы. Сервер честно отдавал ошибку — но отдавал он
// её так, как её сказал драйвер:
//
//   Invalid `prisma2.role.create()` invocation: … Data too long for column
//   'permissions' at row 1
//
// В окне это показывалось всплывающей подсказкой, обрезанной по ширине, а в
// журнале сбоев — обрезанной по длине, ровно на том месте, где стояла причина.
// Человек видел «роль не создаётся» и не мог сделать с этим ничего.
//
// Поэтому причина переводится здесь, один раз, и одинаково для всех разделов:
// что случилось и что с этим делать. Подробность драйвера при этом не
// выбрасывается — она уходит в журнал, где ей и место.

/**
 * Отказ базы одной понятной фразой.
 *
 * Возвращает предложение для человека. Если случай незнакомый — отдаёт
 * последнюю строку сообщения драйвера: она короче и ближе к сути, чем
 * многострочный дамп с телом запроса.
 */
export function explainDbError(error: any, what = 'Запись'): string {
  const raw = String(error?.message || error || '').trim();
  if (!raw) return `${what} не сохранилась: база данных отказала без объяснения.`;

  // Слишком длинное значение. Именно из-за него не сохранялись доступы роли:
  // список прав — это JSON, а колонка в общей базе была на 191 символ
  if (/Data too long|value too long|1406|22001/i.test(raw)) {
    const col = raw.match(/column '([^']+)'|column "([^"]+)"/i);
    const where = col ? ` в поле «${col[1] || col[2]}»` : '';
    return `${what} не сохранилась: значение${where} длиннее, чем позволяет общая база. `
      + 'Программа расширяет такие колонки сама при запуске — перезапустите её; '
      + 'если не помогло, обновите программу у всех, чтобы схема базы догнала.';
  }

  // Колонки нет вовсе — база отстала от программы
  if (/Unknown column|column .* does not exist|no such column|1054|42703/i.test(raw)) {
    return `${what} не сохранилась: в общей базе нет нужного поля — она старее программы. `
      + 'Перезапустите программу: недостающие поля добавляются при запуске.';
  }
  if (/Table .* doesn'?t exist|relation .* does not exist|no such table|1146|42P01/i.test(raw)) {
    return `${what} не сохранилась: в общей базе нет нужной таблицы — она старее программы. `
      + 'Перезапустите программу: недостающие таблицы создаются при запуске.';
  }

  // Повтор уникального значения
  if (/Unique constraint|Duplicate entry|1062|23505/i.test(raw)) {
    return `${what} не сохранилась: такая запись уже есть.`;
  }
  // Ссылка на то, чего нет
  if (/Foreign key constraint|1452|23503/i.test(raw)) {
    return `${what} не сохранилась: она ссылается на запись, которой больше нет. Обновите список.`;
  }
  // Обязательное поле пустое
  if (/cannot be null|not-null constraint|1048|23502/i.test(raw)) {
    const col = raw.match(/column '([^']+)'|column "([^"]+)"/i);
    return `${what} не сохранилась: не заполнено обязательное поле${col ? ` «${col[1] || col[2]}»` : ''}.`;
  }

  // Связи нет. Отдельный случай: тут виновата не запись, а сеть или база
  if (/connection closed|Can'?t reach database|ECONNREFUSED|ETIMEDOUT|connection lost/i.test(raw)) {
    return `${what} не сохранилась: нет связи с общей базой. Проверьте подключение и повторите.`;
  }

  // Незнакомый случай: последняя содержательная строка вместо всего дампа
  const last = raw.split('\n').map(s => s.trim()).filter(Boolean).pop() || raw;
  return `${what} не сохранилась: ${last.slice(0, 200)}`;
}
