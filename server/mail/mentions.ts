/**
 * Что из письма уже есть в программе.
 *
 * Письмо приходит текстом: «просьба подтвердить позиции 20-PT-001, 20-PT-002
 * и согласовать Смета_вентиляция.xlsx». Всё это в Flux существует — тег,
 * тег, документ, — но человек читает письмо, а потом идёт искать их руками:
 * копирует обозначение, открывает Теги, вставляет в поиск. Здесь программа
 * узнаёт свои названия в чужом тексте сама.
 *
 * Разбор в два хода. Сначала из текста выбираются кандидаты — по виду:
 * обозначения через дефис, слова с цифрами, имена файлов с расширением.
 * Потом кандидаты проверяются по базе одним запросом. Обратный порядок —
 * достать из базы все теги и искать каждый в тексте — на проекте с десятью
 * тысячами тегов означал бы десять тысяч поисков на каждое открытое письмо.
 *
 * Модуль чистый: на входе текст, на выходе строки. Разбор проверяется
 * scripts/test-mentions.ts без базы и без сервера.
 */

/** Больше кандидатов из одного письма не берём: дальше идёт мусор подписи. */
const MAX_CANDIDATES = 400;

const LETTER = 'A-Za-zА-Яа-яЁё';

/**
 * Обозначение: куски из букв и цифр, соединённые дефисом, точкой или дробью.
 * Ловит и AHU-2, и 20-PT-001, и у1-мн1, и заодно имена файлов.
 */
const CODE_RE = new RegExp(`[${LETTER}0-9]+(?:[-_./][${LETTER}0-9]+)+`, 'gu');

/**
 * Слитное обозначение с цифрой: AHU2, В1, насос3.
 *
 * Границы слова заданы просмотром, а не \b: \b в JavaScript считает буквами
 * только латиницу, и «В2» через него не находилось вовсе — кириллица для \b
 * не буква, а значит и границы между пробелом и «В» для него нет.
 */
const MIXED_RE = new RegExp(
  `(?<![${LETTER}0-9])(?:[${LETTER}]+[0-9]+|[0-9]+[${LETTER}]+)[${LETTER}0-9]*(?![${LETTER}0-9])`,
  'gu',
);

/** Имя файла — по расширению: на него можно опереться, на пробелы нельзя. */
const FILE_RE = /[^\s"'<>|:*?\\]{1,80}\.(?:xlsx|xlsm|xls|docx|doc|pdf|dwg|dxf|csv|txt|rtf|png|jpe?g|gif|zip|rar|7z)\b/giu;

/**
 * Убираем знаки препинания по краям: «20-PT-001,» → «20-PT-001».
 *
 * Подчёркивание при этом остаётся: с него начинается немало настоящих имён
 * файлов, и «_Смета.xlsx», обрезанная до «Смета.xlsx», в базе уже не нашлась
 * бы. Точка справа сохраняется до последнего шага — иначе от «сметы.pdf»
 * осталось бы «сметы».
 */
const trim = (s: string) => s
  .replace(/^[^\p{L}\p{N}_]+|[^\p{L}\p{N}_.)]+$/gu, '')
  .replace(/[.,;:]+$/, '');

function collect(text: string, re: RegExp, out: Map<string, string>, min: number) {
  for (const m of text.matchAll(re)) {
    const v = trim(m[0]);
    if (v.length < min || v.length > 90) continue;
    const key = v.toLowerCase();
    if (!out.has(key) && out.size < MAX_CANDIDATES) out.set(key, v);
  }
}

/** Кандидаты в обозначения: то, что похоже на тег или на код. */
export function codeCandidates(text: string): string[] {
  const out = new Map<string, string>();
  collect(text, CODE_RE, out, 3);
  collect(text, MIXED_RE, out, 2);
  return [...out.values()];
}

/** Кандидаты в имена файлов: только те, у кого есть расширение. */
export function fileCandidates(text: string): string[] {
  const out = new Map<string, string>();
  collect(text, FILE_RE, out, 5);
  return [...out.values()];
}

/**
 * Регистр в базе и в письме почти никогда не совпадает: в базе «AHU-2», в
 * письме «ahu-2». Сравнение регистронезависимо не во всех базах одинаково,
 * поэтому в запрос кладём оба написания явно.
 */
export function caseVariants(list: string[]): string[] {
  const out = new Set<string>();
  for (const v of list) { out.add(v); out.add(v.toUpperCase()); out.add(v.toLowerCase()); }
  return [...out];
}

/**
 * Названия без опознавательных знаков — книги Конструктора, папки — по виду
 * не отличить от обычных слов. Их ищем наоборот: берём короткий список имён
 * из базы и смотрим, встречается ли имя в тексте целиком.
 *
 * Короткое название из одного слова не берём. Книга «Лист» нашлась бы в
 * каждом письме, где есть лист согласования, лист бумаги или просто слово
 * «лист», — и полоса находок под письмом перестала бы что-либо значить.
 * Название из двух слов уже почти не бывает случайным, поэтому ему хватает
 * пяти букв, а одинокому слову нужно восемь.
 */
export function isDistinctName(name: string): boolean {
  const v = String(name || '').trim();
  if (v.length >= 8) return true;
  return v.includes(' ') && v.length >= 5;
}

export function namesInText(text: string, names: Array<{ id: string; name: string }>) {
  const hay = text.toLowerCase();
  return names.filter((n) => isDistinctName(n.name) && hay.includes(String(n.name).trim().toLowerCase()));
}
