/**
 * ЧЕРНОВИК: карта частей нарисованного котёнка. В приложение не входит.
 *
 * Здесь всё, что привязывает рисунок к скелету. Меняется картинка — меняется
 * только этот файл: сам движок про котёнка ничего не знает.
 *
 * Правила, по которым размечаются вырезы:
 *
 *  1. Координаты — пиксели картинки, начало в левом верхнем углу. Так их
 *     можно просто снять линейкой в любом редакторе.
 *  2. Каждый вырез заходит ПОД тот, что лежит поверх него. Ухо продолжается
 *     вниз, в череп; хвост — внутрь корпуса; лапа — вверх, в грудь. Нахлёста
 *     нужно столько, сколько часть проходит на максимальном угле.
 *  3. Вырез не должен захватывать чужие пиксели, которые окажутся видны.
 *     Корпус тянется вверх узкой полосой шеи, а не во всю ширину, иначе в
 *     слое корпуса поедет вторая, неподвижная голова.
 *  4. Точка вращения ставится там, где часть растёт из соседней, и почти
 *     всегда оказывается скрыта под ней.
 */

export type PartName = 'tail' | 'tailTip' | 'body' | 'earL' | 'earR' | 'head' | 'pawL' | 'pawR';

export interface Part {
  /** Контур выреза, координаты картинки в пикселях. */
  clip: string;
  /** Точка вращения, координаты картинки в пикселях. */
  pivot: [number, number];
}

export interface KittenMap {
  src: string;
  /** Размер картинки в пикселях. */
  w: number;
  h: number;
  /** Пикселей картинки в одной единице сцены. Задаёт рост персонажа. */
  unit: number;
  /** Точка картинки, которая стоит на полу по центру. */
  anchor: [number, number];
  /** Точка посадки: вокруг неё идут наклон и дыхание. */
  seat: [number, number];
  /** Радиус тени в единицах сцены. */
  shadowR: number;
  /** Смягчение краёв выреза в пикселях картинки. 0 — выключить. */
  feather?: number;
  /** Цвет века: берётся с лобика, чуть темнее. */
  lidColor: string;
  /** Цвет ресничной линии — она выезжает из-под века и держит край. */
  lashColor: string;
  eyes?: { cx: number; cy: number; rx: number; ry: number }[];
  parts: Partial<Record<PartName, Part>> & Record<'body' | 'head' | 'earL' | 'earR' | 'tail' | 'pawL' | 'pawR', Part>;
}

const box = (l: number, t: number, r: number, b: number) => `M${l},${t} H${r} V${b} H${l} Z`;

