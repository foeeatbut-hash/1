/**
 * Что сейчас открыто поверх содержимого.
 *
 * Нужно ради одной вещи, которую нельзя решить разметкой: страница браузера —
 * не разметка, а РОДНОЙ СЛОЙ Chromium, положенный поверх окна. Он всегда выше
 * любого HTML, и ни Пуск, ни панель уведомлений, ни диалог поверх него встать
 * не могут в принципе. Для человека это выглядит так, будто панель не
 * открылась.
 *
 * Поэтому у оболочки есть общий счётчик: сколько сейчас открыто поверх. Пока он
 * не ноль, родной слой снимается со сцены и возвращается, когда всё закрыли.
 * Счётчик, а не флаг, потому что открытых бывает несколько сразу — панель и
 * диалог поверх неё, — и закрытие одного не должно возвращать страницу.
 *
 * Правило одно на всех. Прятать страницу «в каждом месте по-своему» — значит
 * однажды забыть, и забудут обязательно.
 */
import { create } from 'zustand';
import { useEffect } from 'react';

interface OverlayState {
  /** Сколько окон, панелей и меню открыто поверх содержимого */
  count: number;
  open: () => void;
  close: () => void;
}

export const useOverlayStore = create<OverlayState>((set) => ({
  count: 0,
  open: () => set((s) => ({ count: s.count + 1 })),
  close: () => set((s) => ({ count: Math.max(0, s.count - 1) })),
}));

/**
 * Пометить, что этот элемент сейчас открыт поверх.
 *
 * Зовётся из самого элемента: он один точно знает, открыт он или нет. Закрытие
 * и размонтирование считаются одинаково — иначе счётчик застрянет на
 * компоненте, который сняли вместе с разделом.
 */
export function useOverlay(active: boolean): void {
  useEffect(() => {
    if (!active) return;
    const { open, close } = useOverlayStore.getState();
    open();
    return close;
  }, [active]);
}

/** Есть ли что-то поверх содержимого — по этому и уступает родной слой */
export const overlayOpen = (): boolean => useOverlayStore.getState().count > 0;
