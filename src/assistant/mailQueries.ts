import { foldRu } from '../handbook/model';

/**
 * Разбор просьб к помощнику про почту.
 *
 * Люди спрашивают не запросами, а словами: «покажи все письма где упоминается
 * 20-PT-001», «письма от Иванова», «переписка про клапаны Гермик». Здесь из
 * такой фразы достаётся то, что можно отдать поиску: слова для поиска по теме
 * и началу письма — и отдельно отправитель.
 *
 * Отправитель отдельно не для красоты. «Письма от Иванова» и «письма про
 * Иванова» — разные просьбы: в первом случае Иванов написал, во втором его
 * обсуждают. Один общий поиск свалил бы их в кучу.
 *
 * Фамилии склоняются: пишут «от Иванова», а в письме стоит «Иванов». Поэтому
 * от имени берётся основа — отрезаются гласные на конце, пока слово не станет
 * коротким. Так «Иванова», «Иванову» и «Ивановым» сходятся к «иванов», и все
 * трое находят одного человека.
 *
 * Модуль чистый: строка на входе, строки на выходе.
 */

export interface MailQuery {
  /** Слова для поиска по теме, отправителю и началу письма */
  q: string;
  /** Кто написал: основа фамилии или адрес */
  from: string;
  /** Как назвать это в ответе: «про 20-PT-001», «от Иванова» */
  label: string;
}

/** Разговор вообще про почту? Без этого письма искать незачем. */
export function asksAboutMail(text: string): boolean {
  return /(письм|почт|переписк|входящ|отправител)/.test(foldRu(text));
}

/**
 * Просят именно найти, а не рассказать, как устроена почта.
 *
 * Кроме прямых просьб («покажи», «найди») сюда попадает и просто названный
 * отбор: «письма от Петрова», «переписка про клапаны». Глагола там нет, но
 * это всё равно поиск — люди так и пишут, коротко.
 */
export function asksToFindMail(text: string): boolean {
  const t = foldRu(text);
  if (!asksAboutMail(t)) return false;
  if (/(как |настро|подключ|подпис|зачем|почему|что так)/.test(t)) return false;
  if (/(найд|найти|покажи|поищ|поиск|ищи|есть ли|все письма|какие письма|упомина|где письм)/.test(t)) return true;
  // «письма от …» и «письма про …» — отбор назван без глагола
  // Окончание слова — через класс букв, а не \w: \w в JavaScript кириллицу
  // за букву не считает, и «письма от Петрова» этим правилом не ловилось.
  return /(письм|почт|переписк)[а-яё]*\s+(от|про|обо|об|по теме|на тему)\s+\S/u.test(t);
}

/** Основа фамилии: «Иванова» → «иванов». Короткие слова не трогаем. */
export function nameStem(word: string): string {
  let w = foldRu(word).replace(/[^\p{L}\p{N}@._-]/gu, '');
  if (w.includes('@')) return w; // адрес почты режем только по «собаке»
  while (w.length > 5 && /[аеиоуыэюя]$/.test(w)) w = w.slice(0, -1);
  // «Ивановым» → «иванов»: согласная на конце после отрезанной гласной
  if (w.length > 6 && /(ым|ом|ем|ой|ей)$/.test(w)) w = w.slice(0, -2);
  return w;
}

const STOP = new Set([
  'все', 'всех', 'мне', 'нужны', 'нужно', 'покажи', 'найди', 'найти', 'поищи', 'пожалуйста',
  'письма', 'письмо', 'писем', 'письме', 'письмах', 'почта', 'почте', 'почту', 'переписка',
  'переписку', 'переписке', 'есть', 'ли', 'где', 'упоминается', 'упоминают', 'упоминался',
  'какие', 'который', 'которые', 'это', 'этот', 'эта', 'эти', 'том', 'про', 'об', 'обо',
]);

/**
 * Разобрать просьбу.
 *
 * Возвращает null, если искать нечего: «покажи письма» без уточнения — это не
 * поиск, а просьба открыть раздел, и обрабатывается она в другом месте.
 */
export function parseMailQuery(text: string): MailQuery | null {
  const src = String(text || '').trim();
  if (!src) return null;

  let rest = src;
  let from = '';
  let fromShown = '';

  // «от Иванова», «от ivanov@», «от специалиста Иванова».
  //
  // Захват останавливаем на предлоге: во фразе «от специалиста Петрова про
  // клапаны» иначе прихватывалось «про», и отправителем становилось оно.
  //
  // Конец слова задан просмотром, а не \b: \b в JavaScript считает буквами
  // только латиницу, и «про\b» перед пробелом не срабатывает вовсе —
  // запрет молча не работал.
  const STOP_AFTER = '(?:про|обо|об|о|по|на|где|с)(?:\\s|$)';
  const byFrom = rest.match(
    new RegExp(`(?:^|\\s)от\\s+((?:(?!${STOP_AFTER})[^\\s,.;]+(?:\\s+|$)){1,3})`, 'iu'),
  );
  if (byFrom) {
    const words = byFrom[1].trim().split(/\s+/).filter(Boolean);
    // Из «специалиста Иванова» берём последнее слово: должность не ищется
    const person = words[words.length - 1];
    from = nameStem(person);
    fromShown = person;
    rest = rest.replace(byFrom[0], ' ');
  }

  // «про X», «о X», «по теме X», «где упоминается X»
  const byAbout = rest.match(/(?:про|обо|об|о|по теме|на тему|где упомина[а-яё]*|с упоминанием)\s+(.+)$/iu);
  let q = byAbout ? byAbout[1] : rest;

  // Убираем служебные слова просьбы — иначе в поиск уедет «покажи все письма»
  q = q
    .replace(/[«»"'`]/g, ' ')
    .split(/\s+/)
    .filter((w) => w && !STOP.has(foldRu(w).replace(/[^\p{L}\p{N}-]/gu, '')))
    .join(' ')
    .replace(/[?!.,;:]+$/, '')
    .trim();

  if (!q && !from) return null;

  const label = [q ? `про «${q}»` : '', fromShown ? `от «${fromShown}»` : '']
    .filter(Boolean).join(' и ');

  return { q: foldRu(q), from, label };
}
