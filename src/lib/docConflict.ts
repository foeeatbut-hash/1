/**
 * Сохранение поверх чужой правки: когда это конфликт и что о нём сказать.
 *
 * Замка на документе нет — двое правят одновременно и видят правки друг друга
 * (Конструктор рассылает операции по сокету). Но есть случай, который сокет не
 * закрывает: ОКНО, ОТСТАВШЕЕ ОТ ЖИЗНИ. Раздел в Flux остаётся смонтированным,
 * когда его окно свёрнуто, и переживает перезапуск программы; связь могла
 * оборваться, ноутбук — уснуть. Такое окно держит в памяти книгу недельной
 * давности и своим автосохранением кладёт её поверх свежей.
 *
 * Заметить это нельзя ничем: ошибки нет, всё «сохранено». Через неделю по
 * ведомости заказывают оборудование, которого в ней уже не должно было быть.
 *
 * Поэтому правило простое и без исключений: документ на сервере изменился с
 * тех пор, как окно его прочитало, — запись не выполняется, человеку показывают
 * разбор. Даже если менял он сам из другого окна: своя правка теряется так же
 * тихо, как чужая.
 */

export interface ConflictInfo {
  /** Кто записал то, что лежит на сервере сейчас */
  who: string;
  /** Когда записал */
  at: string | null;
}

/**
 * Расходится ли то, что окно читало, с тем, что лежит на сервере.
 *
 * Пустая база — старый клиент, который про базу не знает: такому запись
 * разрешаем, иначе обновление программы остановит работу отдела. Он и так
 * работал без проверки до сих пор.
 */
export function isStale(base: string | null | undefined, current: string | null | undefined): boolean {
  if (!base) return false;
  if (!current) return false;
  return new Date(base).getTime() !== new Date(current).getTime();
}

/** Сколько времени прошло — словами, для строки «менял N назад» */
export function agoLabel(at: string | null | undefined, now: Date = new Date()): string {
  if (!at) return 'неизвестно когда';
  const ms = now.getTime() - new Date(at).getTime();
  if (!Number.isFinite(ms)) return 'неизвестно когда';
  const min = Math.floor(ms / 60000);
  if (min < 1) return 'только что';
  if (min === 1) return 'минуту назад';
  if (min < 5) return `${min} минуты назад`;
  if (min < 60) return `${min} минут назад`;
  const h = Math.floor(min / 60);
  if (h === 1) return 'час назад';
  if (h < 5) return `${h} часа назад`;
  if (h < 24) return `${h} часов назад`;
  const d = Math.floor(h / 24);
  if (d === 1) return 'вчера';
  return `${d} дн. назад`;
}

/**
 * Строка разбора: кто и когда занял место под вашей правкой.
 *
 * Своя же правка из другого окна называется своей: «вы меняли» вместо «Иванов
 * менял» — иначе человек ищет виноватого коллегу и не находит.
 */
export function conflictText(info: ConflictInfo, meName: string, now?: Date): string {
  const mine = !!info.who && info.who === meName;
  const who = mine ? 'Вы меняли его в другом окне' : `${info.who || 'Кто-то'} менял его`;
  return `${who} ${agoLabel(info.at, now)}. Ваша правка ещё никуда не записана.`;
}

/** Что можно сделать с конфликтом. Порядок в окне — тот же, что здесь */
