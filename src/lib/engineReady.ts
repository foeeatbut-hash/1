/**
 * Ожидание, пока движок таблиц действительно нарисует лист.
 *
 * Заставка редактора снималась сразу после запуска движка, а лист движок
 * создаёт чуть позже. Между этими двумя мгновениями человек, только что
 * создавший документ, смотрел на белое поле и не понимал, ждать ему или
 * нажимать. Отмерять время на глаз нельзя: на медленной машине оно другое, — и
 * поэтому ждём сам лист.
 *
 * Отдельным модулем, потому что ждать приходится не только в одном месте, а
 * ошибиться здесь легко: бесконечное ожидание оставит человека с заставкой
 * навсегда, поэтому у него всегда есть предел.
 */

/** Сколько ждать, прежде чем показать как есть: лучше пустой лист, чем заставка */
export const READY_TIMEOUT_MS = 4000;
const STEP_MS = 100;

/**
 * `hasSheet` — как спросить у движка, есть ли лист. Проверка передаётся
 * снаружи: этот модуль не должен знать ни про Univer, ни про его версии.
 */
export async function waitForSheet(hasSheet: () => boolean, timeoutMs = READY_TIMEOUT_MS): Promise<boolean> {
  const until = Date.now() + Math.max(0, timeoutMs);
  while (Date.now() < until) {
    let ready = false;
    try { ready = !!hasSheet(); } catch (_) { ready = false; }
    if (ready) return true;
    await new Promise((r) => setTimeout(r, STEP_MS));
  }
  return false;
}
