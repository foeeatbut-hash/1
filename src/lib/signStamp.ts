/**
 * Подпись на документе: где она стоит и что под ней написано.
 *
 * Подпись до этого умела ровно одно — сохраниться в профиле. Ни один документ
 * её не использовал: возможность кончалась там, где должна была начинаться.
 *
 * Здесь правила штампа «Подписать»: строка под росчерком и размер места,
 * которое штамп занимает на листе. Размер важнее, чем кажется: подпись хранится
 * высотой в МИЛЛИМЕТРАХ — именно чтобы не зависеть от разрешения скана, — а
 * пометки на чертеже живут в долях страницы. Между ними нужен перевод, и
 * ошибиться в нём легко: на A1 и на A4 одна и та же доля даёт разный размер.
 *
 * Это не электронная подпись и её не заменяет. Скан живой подписи значит на
 * документе ровно то же, что подпись от руки на распечатке.
 */
import { formatName } from './docFormula';

export interface Signer {
  lastName?: string;
  firstName?: string;
  middleName?: string;
  name?: string;
  /** Должность или роль — то, что пишут второй строкой штампа */
  position?: string;
}

/** Ширина штампа относительно его высоты: росчерк шире, чем выше */
const ASPECT = 3.2;
/** Место под строку с фамилией — доля высоты штампа */
export const CAPTION_PART = 0.38;

/**
 * Строка под подписью: фамилия с инициалами, должность и дата.
 *
 * Дата — та, когда подписали, и она застывает: подпись, у которой дата
 * переезжает при каждом открытии, ничего не значит.
 */
export function signCaption(signer: Signer, when: Date = new Date()): string {
  // «Раупов Х.Х.» — так подпись и пишут в штампах отдела (docFormula.formatName)
  const who = formatName(signer, 'initialsAfter');
  const parts = [who, (signer.position || '').trim(), when.toLocaleDateString('ru-RU')];
  return parts.filter(Boolean).join(' · ');
}

/**
 * Место штампа на странице — в долях страницы.
 *
 * `pageWmm`/`pageHmm` — размеры листа. Если они неизвестны (страница ещё не
 * измерена), берём A4: лучше поставить подпись обычного размера, чем во весь
 * лист. Штамп не вылезает за край — иначе подпись окажется наполовину за
 * пределами листа и на печати обрежется.
 */
export function signBox(
  heightMm: number,
  at: { x: number; y: number },
  page: { wMm?: number; hMm?: number } = {},
): { x: number; y: number; w: number; h: number } {
  const pw = page.wMm && page.wMm > 0 ? page.wMm : 210;
  const ph = page.hMm && page.hMm > 0 ? page.hMm : 297;
  const mm = Math.min(40, Math.max(4, Number(heightMm) || 8));
  // Полная высота штампа — росчерк плюс строка под ним
  const fullMm = mm / (1 - CAPTION_PART);
  const w = Math.min(0.9, (fullMm * ASPECT) / pw);
  const h = Math.min(0.5, fullMm / ph);
  return {
    x: Math.min(Math.max(0, at.x), 1 - w),
    y: Math.min(Math.max(0, at.y), 1 - h),
    w,
    h,
  };
}

/**
 * Что показать, если подписи у человека нет.
 *
 * Молчание здесь — худший ответ: человек нажал «Подписать», ничего не
 * произошло, и он решил, что сломана программа. Поэтому отдельная фраза, и в
 * ней сказано, где подпись заводят.
 */
export const NO_SIGNATURE =
  'Подписи нет. Заведите её в своём профиле: значок с именем → «Подпись».';

/** Место, куда штамп встаёт по умолчанию — правый нижний угол листа */
export const DEFAULT_AT = { x: 0.62, y: 0.86 };
