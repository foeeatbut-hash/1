/**
 * Движок Univer при закрытии редактора оставляет подписку, которая потом лезет
 * в уже закрытый инжектор. На работу редакторов не влияет (проверено E2E),
 * существовало и до расширения набора пресетов.
 *
 * Ловим по форме сообщения, а не по имени службы: имя печатается как есть и
 * после сжатия превращается в пару букв.
 */
const REDI_LOST_SERVICE = /\[redi\].*Expect \d+ dependency item\(s\) for id .* but get 0/;

export const isBenignUniverDisposeError = (msg: string) => REDI_LOST_SERVICE.test(String(msg || ''));

/**
 * Предупреждение браузера: наблюдатель размера не уложился в кадр. Ошибкой
 * программы не является — следующий кадр пересчитывает то же самое. Прилетает
 * от полотна движка и от линейки документа, которая следит за шириной листа.
 */
export const isResizeObserverNoise = (msg: string) => String(msg || '').includes('ResizeObserver loop');
