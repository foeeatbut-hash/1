/**
 * Как сейчас зовут раздел: имя открытого документа, а не имя программы.
 *
 * Оболочка не разбирает адреса и не знает, что такое «документ»: она только
 * показывает сказанное. Раздел сообщает своё имя сам — тем же способом, каким
 * лента сообщает состояние кнопок.
 *
 * Один и тот же раздел живёт в нескольких экземплярах (окно, панель), поэтому
 * имя привязано к экземпляру, а не к разделу: два окна Конструктора зовутся
 * по-разному, и это единственная причина, по которой здесь нужен контекст.
 */
import React from 'react';
import { useWindowStore } from '../store/windowStore';

/** Кто сейчас рассказывает: `win:<id>` у окна, `pane:<id>` у панели */
export const PaneContext = React.createContext<string>('');

/** Идентификатор своего экземпляра — обычно нужен не самому разделу, а раме */
export const usePaneId = (): string => React.useContext(PaneContext);

/**
 * Объявить имя.
 *
 * Пустая строка означает «имени нет» — рама покажет название раздела. Это не
 * то же самое, что не звать функцию вовсе: документ может закрыться, и тогда
 * заголовок обязан вернуться к названию программы, а не остаться от прошлого.
 */
export function useWindowTitle(title: string): void {
  const paneId = React.useContext(PaneContext);
  const setTitle = useWindowStore((s) => s.setTitle);
  React.useEffect(() => {
    if (!paneId.startsWith('win:')) return;
    const id = paneId.slice(4);
    setTitle(id, title.trim());
    // Уход со сцены тоже событие: библиотека Конструктора приходит на место
    // закрытого документа, и заголовок обязан вернуться к имени программы,
    // а не остаться от предыдущего
    return () => setTitle(id, '');
  }, [paneId, title, setTitle]);
}
