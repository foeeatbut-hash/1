/**
 * Режимы помощника.
 *
 * «Демонстрация» была отдельным переключателем во всю ширину под разговором —
 * то есть постоянно занимала место и выглядела главной настройкой, хотя это
 * всего лишь один из способов ответа. Владелец попросил прямо: пусть будет
 * кнопка, а по нажатию — панелька со списком режимов.
 *
 * Список здесь, а не в разметке, ровно ради того, что будет дальше: режимов
 * станет больше, и добавление третьего должно менять одну строку, а не
 * разметку панели.
 */

export type AssistantMode = 'normal' | 'demo';

export interface ModeDef {
  id: AssistantMode;
  /** Как называется на кнопке: коротко, в одно-два слова */
  label: string;
  /** Что изменится — строкой в списке, чтобы не гадать */
  hint: string;
}

export const ASSISTANT_MODES: ModeDef[] = [
  { id: 'normal', label: 'Обычный', hint: 'Отвечает словами и делает, о чём просят' },
  { id: 'demo', label: 'Демонстрация', hint: 'Показывает по шагам прямо в программе' },
];

export const modeOf = (id: AssistantMode): ModeDef =>
  ASSISTANT_MODES.find((m) => m.id === id) || ASSISTANT_MODES[0];

/** Подпись на кнопке: человек должен видеть режим, не открывая список */
export const modeLabel = (id: AssistantMode): string => `Режим: ${modeOf(id).label}`;

/** Подсказка в поле ввода зависит от режима: она и объясняет, что произойдёт */
export const modePlaceholder = (id: AssistantMode): string =>
  (id === 'demo'
    ? 'Что показать? Напишите вопрос…'
    : 'Спросите или скомандуйте: /напомни завтра в 9…');
