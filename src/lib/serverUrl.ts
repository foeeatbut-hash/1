/**
 * Адрес сервера программы: что им может быть, а что нет.
 *
 * Появилось после случая, который стоил рабочего дня. В поле «Сервер компании»
 * на экране входа вписали строку подключения к базе:
 *
 *     mysql://Flux:пароль@192.168.120.14:3306/Flux
 *
 * Поле приняло её молча. После этого КАЖДЫЙ запрос программы строился от этого
 * адреса — `mysql://…@192.168.120.14:3306/Flux/api/health`, — браузер такие
 * запросы вообще не выполняет («URL includes credentials»), программа
 * перестала отвечать и выкинула человека на экран входа. Исправить это изнутри
 * было нечем: экран входа тоже не работал.
 *
 * Ошибка человека здесь закономерна, а не случайна: на экране входа два разных
 * вопроса — «где сервер программы» и «где база данных» — были подписаны почти
 * одинаково (§23.1 дизайна). Развели их отдельным окном подключения к базе, а
 * здесь стоит вторая защита: адресом сервера может быть только http или https.
 *
 * Без React и без сети — правила проверяются скриптом (scripts/test-server-url.ts).
 */

/** Схемы, по которым программа умеет разговаривать с сервером */
const OK_SCHEME = /^https?:\/\//i;

/** Похоже на строку подключения к базе — самая частая ошибка в этом поле */
const DB_SCHEME = /^(mysql|mariadb|postgres|postgresql|mongodb|sqlserver|file|sqlite):/i;

export interface UrlCheck {
  /** Годный адрес, приведённый к виду http(s)://host[:port] без хвостовой черты */
  url: string;
  /** Почему не годится; пустая строка — годится */
  error: string;
}

/**
 * Разобрать то, что ввёл человек.
 *
 * Пустая строка — это законный ответ «встроенный сервер», а не ошибка.
 * Адрес без схемы дополняется http:// — так его и пишут на бумажке.
 */
export function checkServerUrl(raw: string): UrlCheck {
  const s = String(raw || '').trim();
  if (!s) return { url: '', error: '' };

  if (DB_SCHEME.test(s)) {
    return {
      url: '',
      error: 'Это строка подключения к базе данных, а не адрес сервера программы. '
        + 'База настраивается отдельной кнопкой «База» — там же, внизу экрана входа.',
    };
  }

  const withProto = /^[a-zA-Z][a-zA-Z0-9+.-]*:\/\//.test(s) ? s : `http://${s}`;
  if (!OK_SCHEME.test(withProto)) {
    return { url: '', error: 'Адрес сервера начинается с http:// или https://' };
  }

  let parsed: URL;
  try {
    parsed = new URL(withProto);
  } catch (_) {
    return { url: '', error: 'Такой адрес не разобрать. Пример: http://192.168.1.100:3000' };
  }
  if (!parsed.hostname) {
    return { url: '', error: 'В адресе не хватает имени сервера. Пример: http://192.168.1.100:3000' };
  }
  // Логин и пароль в адресе браузер не выполняет вовсе — молча получилась бы
  // неработающая программа
  if (parsed.username || parsed.password) {
    return {
      url: '',
      error: 'В адресе сервера не должно быть имени и пароля. Пример: http://192.168.1.100:3000',
    };
  }

  return { url: `${parsed.protocol}//${parsed.host}`.replace(/\/+$/, ''), error: '' };
}

/** Годен ли адрес — коротко, там где причина не нужна */
export const isServerUrl = (raw: string): boolean => {
  const s = String(raw || '').trim();
  return !!s && !checkServerUrl(s).error;
};

/**
 * Что делать с уже сохранённым адресом.
 *
 * Негодный адрес не применяется никогда: программа возвращается на встроенный
 * сервер и продолжает работать. Молчать при этом нельзя — иначе человек не
 * поймёт, почему он «вроде подключался к серверу компании», а работает один.
 */
export function useSaved(saved: string): { url: string; warn: string } {
  const s = String(saved || '').trim();
  if (!s) return { url: '', warn: '' };
  const r = checkServerUrl(s);
  if (r.error) {
    return {
      url: '',
      warn: `Сохранённый адрес сервера не годится и не применён (${r.error}) `
        + 'Программа работает на встроенном сервере.',
    };
  }
  return { url: r.url, warn: '' };
}

/**
 * Спрятать пароль в строке подключения.
 *
 * Строка подключения к базе попадает и в журналы, и в снимки экрана, и в
 * переписку с поддержкой. Пароль оттуда надо убирать всегда: один раз он уже
 * уехал в диагностический журнал открытым текстом.
 */
export function maskSecrets(text: string): string {
  return String(text || '')
    // схема://пользователь:пароль@хост
    .replace(/([a-zA-Z][a-zA-Z0-9+.-]*:\/\/)([^\s/@:]+):([^\s/@]+)@/g, '$1$2:***@')
    // password=... и pwd=... в строках подключения
    .replace(/\b(password|pwd|pass)\s*=\s*[^\s;&]+/gi, '$1=***');
}
