/**
 * Измерения по чертежу: длина и площадь в настоящих метрах.
 *
 * Считать по чертежу поставщика приходится каждый день — «а этот участок
 * сколько», «влезет ли по высоте». Раньше для этого открывали чертёж в другой
 * программе или прикидывали на глаз.
 *
 * Три величины и ни одной лишней:
 *
 *  • **масштаб листа** — 1:50, 1:100. Задаётся один раз на документ;
 *  • **размер листа в миллиметрах** — его знает сам ПДФ;
 *  • **доля страницы** — в ней живут пометки, чтобы не зависеть от того, как
 *    человек приблизил чертёж.
 *
 * Ошибиться здесь легко и дорого: перепутать сторону листа при пересчёте по
 * горизонтали и вертикали, забыть про масштаб, посчитать площадь в единицах
 * длины. Такую ошибку не видно — видно только неправильное число, которое
 * человек перенесёт в расчёт.
 */

/** Готовые масштабы: то, что стоит в штампах чаще всего */
export const SCALES = [1, 2, 5, 10, 20, 25, 50, 100, 200, 500, 1000];

export interface Sheet {
  /** Ширина листа в миллиметрах */
  wMm: number;
  /** Высота листа в миллиметрах */
  hMm: number;
  /** Знаменатель масштаба: 50 для 1:50. Единица — чертёж в натуральную величину */
  scale: number;
}

/** Точки страницы (1/72 дюйма) в миллиметры */
export const PT_TO_MM = 25.4 / 72;

/**
 * Длина отрезка, заданного долями страницы, в миллиметрах НАТУРЫ.
 *
 * По горизонтали доля умножается на ширину листа, по вертикали — на высоту:
 * лист не квадратный, и общий множитель дал бы разную ошибку по осям. Потом
 * теорема Пифагора — и умножение на масштаб.
 */
export function lengthMm(dx: number, dy: number, sheet: Sheet): number {
  const mmX = dx * (sheet.wMm || 0);
  const mmY = dy * (sheet.hMm || 0);
  const onPaper = Math.sqrt(mmX * mmX + mmY * mmY);
  return onPaper * Math.max(1, sheet.scale || 1);
}

/**
 * Площадь прямоугольника, заданного долями страницы, в квадратных метрах.
 *
 * Масштаб входит в квадрате: 1:100 уменьшает длину в сто раз, а площадь — в
 * десять тысяч. Это то самое место, где ошибаются, и число получается меньше
 * настоящего на два порядка.
 */
export function areaM2(w: number, h: number, sheet: Sheet): number {
  const k = Math.max(1, sheet.scale || 1);
  const mmW = Math.abs(w) * (sheet.wMm || 0) * k;
  const mmH = Math.abs(h) * (sheet.hMm || 0) * k;
  return (mmW * mmH) / 1_000_000;
}

/**
 * Число человеку: миллиметры до метра, дальше метры.
 *
 * «12345.678 мм» не читается; на чертеже пишут либо мм, либо м, и переход
 * происходит там же, где в голове у инженера.
 */
export function lengthLabel(mm: number): string {
  const v = Math.abs(mm);
  if (!Number.isFinite(v)) return '—';
  if (v < 1000) return `${Math.round(v)} мм`;
  return `${(v / 1000).toFixed(v < 10000 ? 2 : 1)} м`;
}

export function areaLabel(m2: number): string {
  if (!Number.isFinite(m2)) return '—';
  if (m2 < 0.01) return `${Math.round(m2 * 1_000_000)} мм²`;
  return `${m2.toFixed(m2 < 10 ? 2 : 1)} м²`;
}

/** Подпись масштаба: 1:1 — это «натуральная величина», а не «1:1» */
export function scaleLabel(scale: number): string {
  return scale <= 1 ? '1:1 (натуральная величина)' : `1:${scale}`;
}

/**
 * Что показать рядом с измерением.
 *
 * Размеров листа может не быть (страница ещё не измерена) — тогда честно
 * говорим, что мерить нечем, вместо числа, взятого из ниоткуда.
 */
export function measureLabel(
  kind: 'length' | 'area',
  box: { dx: number; dy: number },
  sheet: Sheet | null,
): string {
  if (!sheet || !sheet.wMm || !sheet.hMm) return 'Размер листа неизвестен — мерить нечем';
  return kind === 'length'
    ? lengthLabel(lengthMm(box.dx, box.dy, sheet))
    : areaLabel(areaM2(box.dx, box.dy, sheet));
}
