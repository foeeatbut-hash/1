/**
 * Родной слой страницы уступает дорогу — и возвращается, когда всё закрыли.
 *
 * Проверка написана по двум жалобам владельца, у которых одна причина.
 * Страница браузера — не разметка, а родной слой Chromium поверх окна: он выше
 * любого HTML, и Пуск, панель уведомлений или диалог, открытые поверх браузера,
 * оказываются ПОД страницей. Для человека это выглядит как «панель не
 * открылась».
 *
 * Считаем именно счётчиком, а не флагом: открытых бывает несколько сразу —
 * панель и диалог поверх неё, — и закрытие одного не должно возвращать
 * страницу раньше времени. Ошибиться тут легко, а увидеть ошибку можно только
 * на живом браузере в одном конкретном сочетании окон.
 *
 * Запуск: npx tsx scripts/test-overlay.ts
 */
import { useOverlayStore, overlayOpen } from '../src/store/overlayStore';

let failed = 0;
const check = (name: string, cond: boolean, got?: unknown) => {
  if (cond) return;
  failed++;
  console.error(`  ✗ ${name}${got === undefined ? '' : ` — получили ${JSON.stringify(got)}`}`);
};

const { open, close } = useOverlayStore.getState();
const count = () => useOverlayStore.getState().count;

console.log('Пока ничего не открыто — страница видна');
{
  check('счётчик пуст', count() === 0, count());
  check('уступать некому', !overlayOpen());
}

console.log('Открытое поверх снимает страницу со сцены');
{
  open();
  check('счётчик считает', count() === 1, count());
  check('страница уступает', overlayOpen());
  close();
  check('и возвращается', !overlayOpen(), count());
}

console.log('Открытых бывает несколько сразу');
{
  open();            // панель уведомлений
  open();            // диалог поверх неё
  check('оба посчитаны', count() === 2, count());
  close();           // закрыли диалог
  check('страница ещё уступает — панель осталась', overlayOpen(), count());
  close();           // закрыли панель
  check('теперь возвращается', !overlayOpen(), count());
}

console.log('Лишнее закрытие не уводит счётчик в минус');
{
  close(); close(); close();
  check('счётчик не отрицательный', count() === 0, count());
  check('страница видна', !overlayOpen());
  // Минус был бы хуже нуля: одно открытие после него не вернуло бы уступку,
  // и панель снова оказалась бы под страницей
  open();
  check('после этого открытие всё равно работает', overlayOpen(), count());
  close();
}

if (failed) {
  console.error(`\nПровалено проверок: ${failed}`);
  process.exit(1);
}
console.log('\nВсе проверки уступки родного слоя пройдены');
