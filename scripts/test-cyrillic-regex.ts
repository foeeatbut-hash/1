/**
 * Кириллица и границы слова в регулярных выражениях.
 *
 * В JavaScript `\w` и `\b` считают буквами только латиницу. Поэтому
 * «технологическ\w*\s*позици» НЕ совпадает с «Технологическая позиция», а
 * «проект\b» не совпадает вообще ни с чем: после «т» в конце строки границы
 * слова нет, потому что «т» для движка не буква.
 *
 * Такая ошибка не падает и не пишется в журнал. Она просто тихо ничего не
 * находит, и на импорте опросного листа человек видит, что позиция не
 * распозналась, — без единого следа в коде, куда смотреть.
 *
 * Здесь проверяются вылеченные места и стоит сторож, чтобы эта же ошибка не
 * вернулась новым кодом.
 *
 * Запуск: npx tsx scripts/test-cyrillic-regex.ts
 */
import { readFileSync } from 'fs';
import { ADMIN_LABEL_RE, ADMIN_TAG_RE } from '../src/import/dictionary';
import { needsContext } from '../src/assistant/context';

let failed = 0;
const check = (name: string, cond: boolean, got?: unknown) => {
  if (cond) return;
  failed++;
  console.error(`  ✗ ${name}${got === undefined ? '' : ` — получили ${JSON.stringify(got)}`}`);
};

console.log('Подписи административной шапки');
{
  check('«Проект» узнаётся', ADMIN_LABEL_RE.test('Проект'));
  check('«Проект:» тоже', ADMIN_LABEL_RE.test('Проект:'));
  // А «проектные данные» — это уже не подпись поля «Проект», и забирать их
  // в шапку нельзя: пропадут данные карточки. (Слово «документация» в шапку
  // как раз входит, поэтому для проверки взята другая пара слов.)
  check('«Проектные данные» — не оно', !ADMIN_LABEL_RE.test('Проектные данные'));
  check('латинское project по-прежнему узнаётся', ADMIN_LABEL_RE.test('Project no'));
}

console.log('Подпись технологической позиции');
{
  // Самая частая подпись в русских опросных листах: до правки не совпадала
  // никогда, и позиция не распознавалась
  check('«Технологическая позиция»', ADMIN_TAG_RE.test('Технологическая позиция'));
  check('«Технологическая позиция (Tag)»', ADMIN_TAG_RE.test('Технологическая позиция (Tag)'));
  check('«технологической позиции»', ADMIN_TAG_RE.test('технологической позиции'));
  check('«Tag No» по-прежнему', ADMIN_TAG_RE.test('Tag No'));
  check('«код системы» по-прежнему', ADMIN_TAG_RE.test('код системы'));
}

console.log('Указательные слова помощника');
{
  // «тегов» содержит «его»: с \W это делало обычный вопрос вопросом про
  // открытый документ
  check('«сколько тегов в проекте» — вопрос сам по себе', !needsContext('сколько тегов в проекте'));
  check('«кто его правил» — про открытое', needsContext('кто его правил'));
  check('«их сколько?» — про открытое', needsContext('их сколько?'));
  check('«статистика» не считается указанием', !needsContext('статистика'));
}

console.log('Ранее мёртвые выражения ожили');
{
  // Проверяем текстом по исходнику: сами выражения лежат внутри функций и
  // наружу не выведены, а поднимать разбор XML ради одного вопроса «есть ли
  // тут \b» — дороже, чем прочитать строку
  const parser = readFileSync('server/equipmentParser.ts', 'utf8');
  // XML с русскими тегами: «<установка …>» не находилось вовсе, и файл
  // оборудования импортировался пустым — без единого следа в журнале
  for (const dead of ['установка|unit)\\b', 'моноблок|mb)\\b', 'блок|component|element)\\b',
                      'группа|section)\\b', 'параметр|property)\\b']) {
    check(`граница «${dead.split('|')[0]}» больше не через \\b`, !parser.includes(dead), dead);
  }
  check('границы имён тегов заданы просмотром', parser.includes('(?=[\\s/>])'));

  const fields = readFileSync('src/capture/fields.ts', 'utf8');
  check('подпись «тег» больше не через \\b', !fields.includes('\\bтег\\b'));
  check('подпись «тип» больше не через \\b', !fields.includes('тип\\b'));

  const extractors = readFileSync('src/import/extractors.ts', 'utf8');
  check('<характеристика> больше не через \\b', !extractors.includes('характеристика)\\b'));

  const digest = readFileSync('src/translate/mailDigest.ts', 'utf8');
  check('«ревизия A» в письме больше не через \\b', !digest.includes('рев\\.?)\\s*([A-Z0-9]{1,2})\\b'));
}

console.log('Проверка ловит ловушку, а не делает вид');
{
  // Сторож без самопроверки бесполезен: убедимся, что мёртвое выражение
  // действительно мёртвое, а вылеченное — живое
  check('«\\bтег\\b» и правда ничего не находит в «номер тег »', !/\bтег\b/.test('номер тег '));
  check('явная граница находит', /(^|[^а-яё])тег([^а-яё]|$)/.test('номер тег '));
  check('«<установка\\b» и правда мёртвое', !/<установка\b/.test('<установка name="У1">'));
  check('просмотр вместо \\b работает', /<установка(?=[\s/>])/.test('<установка name="У1">'));
}

if (failed) {
  console.error(`\nПровалено проверок: ${failed}`);
  process.exit(1);
}
console.log('\nВсе проверки кириллицы в выражениях пройдены');
