def is_service_header(header: str) -> bool:
    """True, если столбец не является атрибутом изделия.

    «Поз. обозначение» служебным не считается: это полноценный атрибут E3,
    он же используется для поиска изделия.
    """
    key = header_key(header)
    if not key:
        return True
    return key in SERVICE_HEADERS


def attribute_headers_of(headers: list[str]) -> list[str]:
    """Из шапки файла выбирает столбцы, которые надо писать в изделие."""
    return [h for h in headers if not is_service_header(h)]
