/**
 * Правила скачивания обновления — сторона главного процесса.
 *
 * Здесь то, что решается там, где качается файл: кому можно показать токен,
 * похоже ли скачанное на программу и как назвать человеку отказ сервера.
 * В окне настроек живут другие правила (src/lib/updates.ts) — сравнение версий
 * и что показывать на кнопке; смешивать их нельзя: главный процесс не тянет
 * код окна, это граница слоёв (см. scripts/test-architecture.ts).
 *
 * Отдельным файлом, а не внутри main.ts, потому что ошибиться тут легко, а
 * увидеть ошибку можно только на чужой машине в день выпуска. Проверяется
 * скриптом scripts/test-updates.ts.
 */

/**
 * Свой ли это сервер.
 *
 * Токен сессии уходит только на него. Раньше заголовок Authorization
 * добавлялся к любому адресу: если администратор выкладывал релиз прямой
 * ссылкой на чужой хост, тот отвечал отказом на непонятный ему токен — и
 * обновление не скачивалось вовсе. А заодно токен сотрудника уезжал наружу.
 */
export function sameServer(url: string, base: string): boolean {
  try {
    const a = new URL(url);
    const b = new URL(base);
    return a.host === b.host && a.protocol === b.protocol;
  } catch (_) { return false; }
}

/** Файл меньше этого — не программа, а обрывок или страница с ошибкой */
export const MIN_EXE_BYTES = 5 * 1024 * 1024;

/**
 * Похоже ли скачанное на программу для Windows. Пустая строка — годится.
 *
 * Проверка не формальность. Сервер, отдавший вместо файла страницу с ошибкой
 * («нужен вход», «файл не найден»), возвращает её кодом 200 — и без этой
 * проверки такая страница легла бы на место работающей программы. Человек
 * остался бы без программы вовсе, и восстановить её было бы уже нечем.
 *
 * Признак — сигнатура MZ в первых двух байтах: с неё начинается любой exe.
 */
export function badPackage(head: number[] | null | undefined, size: number): string {
  if (!head || head.length < 2 || head[0] !== 0x4d || head[1] !== 0x5a) {
    return 'Скачался не файл программы. Похоже, сервер вернул страницу с ошибкой вместо exe.';
  }
  if (size < MIN_EXE_BYTES) {
    return `Файл обновления подозрительно мал (${Math.round(size / 1048576)} МБ). Загрузка оборвалась.`;
  }
  return '';
}

/**
 * Отказ сервера — человеческими словами.
 *
 * «Server responded with status code 401» человеку не говорит ничего, и он
 * идёт с этим к владельцу программы. Каждый код здесь означает конкретную
 * поправимую вещь, и сказать надо именно её.
 */
export function downloadError(status: number, serverText = ''): string {
  const said = String(serverText || '').trim().slice(0, 200);
  if (status === 401 || status === 403) {
    return 'Сервер не принял вход при скачивании. Войдите в программу заново и повторите.';
  }
  if (status === 404) {
    return 'Файла этой версии на сервере нет. Администратору нужно загрузить exe в разделе «Обновления».';
  }
  if (status >= 500) return `Сервер обновлений ответил ошибкой${said ? `: ${said}` : ''}.`;
  return said || `Сервер обновлений ответил кодом ${status}.`;
}

/** Имя скачанного файла: с версией и без посторонних знаков в пути */
export const installerName = (version: string): string =>
  `Flux-${String(version || '').replace(/[^0-9a-zA-Z.\-]/g, '')}.exe`;
